"""URDF export (ROS / Gazebo / PyBullet / Isaac) from the same link tree."""
from __future__ import annotations

from pathlib import Path

import numpy as np

from . import params as P
from . import robot as R
from .massprops import link_inertials
from .cad.catalog import all_parts

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sim" / "models" / "urdf" / "aquabot.urdf"


def rpy_from_R(Rm):
    sy = -Rm[2, 0]
    pitch = np.arcsin(np.clip(sy, -1, 1))
    if abs(np.cos(pitch)) > 1e-9:
        roll = np.arctan2(Rm[2, 1], Rm[2, 2])
        yaw = np.arctan2(Rm[1, 0], Rm[0, 0])
    else:
        roll = np.arctan2(-Rm[1, 2], Rm[1, 1]); yaw = 0.0
    return roll, pitch, yaw


def R_from_rpy(r, p, y):
    cr, sr, cp, sp, cy, sy = np.cos(r), np.sin(r), np.cos(p), np.sin(p), np.cos(y), np.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def f(v):
    return " ".join(f"{x:.10g}" for x in v)


def generate(mesh_prefix="package://aquabot_description/meshes/") -> str:
    tree = R.build_tree()
    inert = link_inertials()
    parts = all_parts()
    L = ['<?xml version="1.0"?>', f'<!-- AquaBot v{P.VERSION} — generated by aquabot/urdf.py -->', '<robot name="aquabot">']
    mats = {}
    for name, l in tree.items():
        m, c, I = inert[name]
        L.append(f'  <link name="{name}">')
        L.append(f'    <inertial><origin xyz="{f(np.asarray(c)/1000)}" rpy="0 0 0"/><mass value="{m/1000:.6f}"/>')
        Ik = np.asarray(I) * 1e-9
        L.append(f'      <inertia ixx="{Ik[0,0]:.4e}" ixy="{Ik[0,1]:.4e}" ixz="{Ik[0,2]:.4e}" iyy="{Ik[1,1]:.4e}" iyz="{Ik[1,2]:.4e}" izz="{Ik[2,2]:.4e}"/></inertial>')
        for it in l.instances:
            rr = rpy_from_R(it.T[:3, :3])
            c4 = parts[it.part].rgba
            mats[it.part] = c4
            L.append(f'    <visual name="{it.name}"><origin xyz="{f(it.T[:3,3]/1000)}" rpy="{f(rr)}"/>'
                     f'<geometry><mesh filename="{mesh_prefix}{it.part}.stl" scale="0.001 0.001 0.001"/></geometry>'
                     f'<material name="{it.part}_mat"/></visual>')
        if name.endswith("_tibia"):
            L.append(f'    <collision><origin xyz="0 0 {-P.L_TIBIA/1000:.4f}"/><geometry><sphere radius="{P.FOOT_R/1000:.4f}"/></geometry></collision>')
        if name == "base":
            L.append('    <collision><origin xyz="0 0 -0.005"/><geometry><box size="0.19 0.092 0.09"/></geometry></collision>')
        L.append('  </link>')
        if l.joint:
            j = l.joint
            jt = "revolute" if j.type == "revolute" else "prismatic"
            M = l.origin
            rr = rpy_from_R(M[:3, :3])
            lo, hi = (j.lower, j.upper) if j.type == "revolute" else (j.lower / 1000, j.upper / 1000)
            spec = P.DS3218 if j.actuator == "DS3218" else P.MG90S
            effort = spec.stall_torque if j.type == "revolute" else 18.0
            vel = spec.speed if j.type == "revolute" else 0.06
            L.append(f'  <joint name="{j.name}" type="{jt}">')
            L.append(f'    <parent link="{l.parent}"/><child link="{name}"/>')
            L.append(f'    <origin xyz="{f(M[:3,3]/1000)}" rpy="{f(rr)}"/><axis xyz="{f(j.axis)}"/>')
            L.append(f'    <limit lower="{lo:.5f}" upper="{hi:.5f}" effort="{effort:.3f}" velocity="{vel:.2f}"/>')
            if j.mimic:
                src, k = j.mimic
                if j.type == "revolute":   # pinion follows a prismatic joint: m -> rad
                    k = k * 1000.0
                L.append(f'    <mimic joint="{src}" multiplier="{k:.6f}" offset="0"/>')
            L.append('  </joint>')
    for k, c in mats.items():
        L.insert(3, f'  <material name="{k}_mat"><color rgba="{f(c)}"/></material>')
    L.append('</robot>')
    return "\n".join(L) + "\n"


def write():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generate())
    mesh_dir = OUT.parent / "meshes"
    mesh_dir.mkdir(exist_ok=True)
    src = ROOT / "sim" / "models" / "meshes"
    if src.exists():
        import shutil
        for p in src.glob("*.stl"):
            shutil.copy(p, mesh_dir / p.name)
    return OUT


def fk_from_urdf(path: Path, q: dict) -> dict:
    """Minimal URDF forward kinematics (used by QA to cross-check the export)."""
    import xml.etree.ElementTree as ET
    root = ET.parse(path).getroot()
    joints = {}
    for j in root.findall("joint"):
        o = j.find("origin")
        xyz = np.array([float(v) for v in o.get("xyz").split()])
        rpy = [float(v) for v in o.get("rpy").split()]
        ax = np.array([float(v) for v in j.find("axis").get("xyz").split()])
        child = j.find("child").get("link"); parent = j.find("parent").get("link")
        mim = j.find("mimic")
        joints[child] = (j.get("name"), j.get("type"), parent, xyz, R_from_rpy(*rpy), ax,
                         (mim.get("joint"), float(mim.get("multiplier"))) if mim is not None else None)
    qq = dict(q)
    for child, (n, t, par, xyz, Rm, ax, mim) in joints.items():
        if mim:
            qq[n] = mim[1] * qq.get(mim[0], 0.0)
    out = {"base": np.eye(4)}

    def get(link):
        if link in out:
            return out[link]
        n, t, par, xyz, Rm, ax, mim = joints[link]
        Tp = get(par)
        M = np.eye(4); M[:3, :3] = Rm; M[:3, 3] = xyz
        J = np.eye(4)
        v = qq.get(n, 0.0)
        if t == "revolute":
            J[:3, :3] = R.axis_angle(ax, v)
        else:
            J[:3, 3] = ax * v
        out[link] = Tp @ M @ J
        return out[link]
    for c in joints:
        get(c)
    return out
