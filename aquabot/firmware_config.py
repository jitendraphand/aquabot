"""Generate firmware/aquabot/config.h from params.py (single source of truth)."""
from __future__ import annotations

from pathlib import Path

import numpy as np

from . import params as P
from .cad import parts_body as PB
from .robot import build_tree

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "aquabot" / "config.h"

# PCA9685 channel map (legs) and ESP32 GPIO map (arm + pump)
LEG_CH = {"FL": (0, 1, 2), "FR": (4, 5, 6), "RL": (8, 9, 10), "RR": (12, 13, 14)}
ARM_GPIO = dict(yaw=25, shoulder=26, elbow=27, wrist=32, grip=33)   # avoids strapping pins 12/14
PINS = dict(SDA=21, SCL=22, PUMP=13, VBAT=35, LED=2, TOF_XSHUT=4)
# servo direction (+1: positive joint angle = positive servo angle), set at assembly
DIRS = {"FL": (1, -1, -1), "FR": (1, 1, 1), "RL": (1, -1, -1), "RR": (1, 1, 1)}


def generate() -> str:
    t = build_tree()
    lim = lambda n: (np.degrees(t[n].joint.lower), np.degrees(t[n].joint.upper))
    L = []
    a = L.append
    a("// AUTO-GENERATED by aquabot/firmware_config.py from aquabot/params.py — do not edit.")
    a(f"// AquaBot v{P.VERSION}")
    a("#pragma once")
    a("")
    a("// ---- geometry (mm) ----")
    for k, v in dict(L_FEMUR=P.L_FEMUR, L_TIBIA=P.L_TIBIA, FOOT_R=P.FOOT_R, HIP_X=P.J1_HORN_X, HIP_Y=P.Y_J1,
                     J2_DX=P.J2_DX, J2_DY=P.J2_DY, J2_DZ=P.J2_DZ, L_ARM1=P.L_ARM1, L_ARM2=P.L_ARM2,
                     L_TCP=P.L_TCP, NOZZLE_A=P.NOZZLE_OFF[0], NOZZLE_B=P.NOZZLE_OFF[1],
                     SHOULDER_X=PB.YAW["x"], SHOULDER_Y=PB.YAW["y"], SHOULDER_Z=P.ARM_SHOULDER_Z,
                     STAND_HEIGHT=P.STAND_HEIGHT, CROUCH_HEIGHT=P.CROUCH_HEIGHT,
                     STANCE_DX=P.GAIT["stance_dx"], STANCE_DY=P.GAIT["stance_dy"], FOOT_IN=P.GAIT["foot_in"],
                     GRIP_STROKE=P.GRIP_STROKE).items():
        a(f"#define {k:<14s} {float(v):.4f}f")
    a("")
    a("// ---- joint limits (deg) ----")
    for leg in P.LEGS:
        for j, ln in zip(("ABD", "PITCH", "KNEE"), (f"{leg}_hip", f"{leg}_femur", f"{leg}_tibia")):
            lo, hi = lim(ln)
            a(f"#define LIM_{leg}_{j}_LO {lo:9.3f}f")
            a(f"#define LIM_{leg}_{j}_HI {hi:9.3f}f")
    for j, ln in zip(("YAW", "SHOULDER", "ELBOW", "WRIST"), ("arm_turntable", "arm_upper", "arm_fore", "arm_wrist")):
        lo, hi = lim(ln)
        a(f"#define LIM_ARM_{j}_LO {lo:9.3f}f")
        a(f"#define LIM_ARM_{j}_HI {hi:9.3f}f")
    a("")
    a("// ---- crawl gait ----")
    for k, v in P.CRAWL.items():
        a(f"#define CRAWL_{k.upper():<12s} {float(v):.4f}f")
    a("")
    a("// ---- water ----")
    a(f"#define PUMP_ML_PER_S  {P.PUMP['flow_ml_min']/60.0:.4f}f")
    a(f"#define TANK_ML        {P.TANK_TARGET_ML:.1f}f")
    a(f"#define NOZZLE_ORIFICE {P.NOZZLE_ORIFICE:.2f}f")
    a("")
    a("// ---- servos ----")
    a(f"#define DS_RANGE_DEG   {P.DS3218.range_deg:.1f}f   // 500..2500 us")
    a(f"#define MG_RANGE_DEG   {P.MG90S.range_deg:.1f}f")
    a(f"#define DS_MAX_DPS     {np.degrees(P.DS3218.speed)*0.95:.1f}f  // slew limit (deg/s)")
    a("static const uint8_t LEG_CH[4][3] = {" + ", ".join("{%d,%d,%d}" % LEG_CH[l] for l in P.LEGS) + "};")
    a("static const int8_t  LEG_DIR[4][3] = {" + ", ".join("{%d,%d,%d}" % DIRS[l] for l in P.LEGS) + "};")
    a("// per-joint zero offsets (deg), measured with the calibration jig — `calib` command")
    a("extern float LEG_OFFSET[4][3];   // defined in hal.cpp")
    for k, v in ARM_GPIO.items():
        a(f"#define PIN_ARM_{k.upper():<9s} {v}")
    for k, v in PINS.items():
        a(f"#define PIN_{k:<12s} {v}")
    a("#define PCA9685_ADDR   0x40")
    a("#define CTRL_HZ        100")
    return "\n".join(L) + "\n"


def write():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generate())
    return OUT


if __name__ == "__main__":
    print(write())
